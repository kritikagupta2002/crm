/**
 * Calculates stock availability and active status for an inventory item
 * given the list of all assignments.
 */
export function calculateItemStock(item, assignments = []) {
  const itemAssignments = assignments.filter(
    (a) => a.inventoryItemId === item.id || (item.assetId && a.assetId === item.assetId),
  )

  const activeAssignedQuantity = itemAssignments
    .filter((a) => a.status === 'Assigned')
    .reduce((sum, a) => sum + (Number(a.quantity) || 0), 0)

  const returnedQuantity = itemAssignments
    .filter((a) => a.status === 'Returned')
    .reduce((sum, a) => sum + (Number(a.quantity) || 0), 0)

  const totalQuantity = Number(item.quantity) || 0
  const availableQuantity = Math.max(0, totalQuantity - activeAssignedQuantity)

  let status = 'Available'
  if (totalQuantity <= 0 || (availableQuantity <= 0 && activeAssignedQuantity === 0)) {
    status = 'Out of Stock'
  } else if (availableQuantity <= 0 && activeAssignedQuantity > 0) {
    status = 'Assigned'
  } else if (activeAssignedQuantity > 0 && availableQuantity > 0) {
    status = 'Partially Assigned'
  } else {
    status = 'Available'
  }

  return {
    ...item,
    totalQuantity,
    assignedQuantity: activeAssignedQuantity,
    availableQuantity,
    returnedQuantity,
    status,
    activeAssignmentsCount: itemAssignments.filter((a) => a.status === 'Assigned').length,
    totalAssignmentsCount: itemAssignments.length,
  }
}
